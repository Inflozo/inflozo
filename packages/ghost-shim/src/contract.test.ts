test('{{img_url}} — a Ghost-hosted image at every image_sizes key, byte for byte', () => {
  assertBoth('{{img_url}}', (major) => {
    const rec = recording(major, 'index', '{{img_url}}')
    // the image the recorder uploaded — recorded, so the test feeds the shim the same INPUT Ghost
    // had. It is an ABSOLUTE same-origin URL, which is the case that matters: Ghost answers with a
    // RELATIVE sized URL, so a canvas that passed the value through would serve the original file.
    const src = rec.uploaded_image
    assert.ok(typeof src === 'string' && src !== '', 'the recording does not say which image it sized')
    assert.ok(src.startsWith(rec.site), 'the recorded image is not same-origin — the case is not exercised')
    const site = rec.site

    for (const key of Object.keys(IMAGE_SIZES)) {
      const want = recorded(major, 'index', 'IMG', `hosted_${key}`, `{{img_url size="${key}"}}`)
      // NOT normalised, on either side. This is the assertion the WYSIWYG promise rests on.
      assert.equal(imgUrl(src, key, { siteUrl: site }), want, `img_url size="${key}" drifted from Ghost`)
    }
    assert.equal(
      imgUrl(src, undefined, { siteUrl: site }),
      recorded(major, 'index', 'IMG', 'hosted_nosize', '{{img_url}} with no size'),
    )
    const first = Object.keys(IMAGE_SIZES)[0] as string
    assert.equal(
      imgUrl(src, first, { siteUrl: site, absolute: true }),
      recorded(major, 'index', 'IMG', 'hosted_absolute', '{{img_url absolute="true"}}'),
    )
    assert.equal(
      imgUrl(src, first, { siteUrl: site, format: 'webp' }),
      recorded(major, 'index', 'IMG', 'hosted_webp', '{{img_url format="webp"}}'),
    )
  })
})

