test('AD-36 — a hostile Ghost URL is inert and the legitimate one beside it still works', () => {
  for (const hostile of [
    'javascript:alert(1)',
    'JaVaScRiPt:alert(1)',
    'java\nscript:alert(1)',
    'data:text/html,<script>alert(1)</script>',
    'vbscript:msgbox(1)',
    // narrower than safeUrl's USER allow-list, deliberately: a mailto: in @site.logo is not a
    // feature, it is a compromised or confused field (SPINE Conventions row)
    'mailto:someone@example.com',
    'tel:+15551234',
  ]) {
    assert.equal(ghostUrl(hostile), '#', `${hostile} was not neutralised`)
  }
  assertBoth('Ghost URL fields', (major) => {
    // the legitimate half, from the recording rather than from an example
    const site = recording(major, 'index', 'Ghost URL fields').site
    assert.equal(ghostUrl(site), site)
    const cover = recorded(major, 'index', 'SITE', 'cover_image', '@site.cover_image')
    if (cover !== '') assert.equal(ghostUrl(cover), cover, 'a real Ghost image URL was mangled')
    const url = recorded(major, 'post', 'POST', 'url', '{{url}}')
    assert.equal(ghostUrl(url), url, 'a relative Ghost URL must survive')
  })
})

test('AD-36 / DW-95 — a Ghost colour that is not a colour falls back, and a real one survives', () => {
  // Ghost stores accent_color VERBATIM: all four of these were ACCEPTED on both live majors
  // (MEASUREMENTS §21e, executed), so the value crossing into a CSS declaration is not necessarily
  // a colour. The shim calls the LIBRARY's parser — one copy, which is the whole of DW-95.
  for (const hostile of [
    'red;}body{display:none',
    '#fff;background:url(x)',
    '#fff;width:100vw',
    '#f00;/* c */color:red',
    'red',
  ]) {
    assert.equal(ghostColor(hostile), 'var(--accent)', `${hostile} was not neutralised`)
  }
  assert.equal(ghostColor('#f0f'), '#f0f', 'the legitimate value beside it must still work')
  assert.equal(ghostColor('rgb(255, 0, 255)'), 'rgb(255, 0, 255)')
  assertBoth('a Ghost colour', (major) => {
    const accent = recorded(major, 'index', 'SITE', 'accent_color', '@site.accent_color')
    assert.equal(ghostColor(accent), accent, `the site's real accent colour ${accent} was refused`)
    // and it is the library's one copy, not a second parser grown here
    assert.equal(ghostColor(accent), safeCssColor(accent, '--accent'))
  })
})

