// NFR-6(c2) — the shim's contract tests, against RECORDED real-Ghost output.
//
// "Shim fidelity is enforced by contract tests asserting each shimmed helper's output matches
// recorded real-Ghost output for a fixed input set" (FR-H5), per-commit and OFFLINE, "with image
// URLs compared, not normalized away, because the canvas shim emits Ghost-shaped sized URLs and
// srcset rather than passing paths through" (NFR-6(c2)).
//
// Three properties this file is built to have, each learned expensively:
//
//   1. **It never skips.** Standing rule 2: a result whose control did not pass is not a result.
//      `recorded()` THROWS a sentence naming the helper and the capture command when a recording is
//      absent, so a missing fixture fails the suite rather than quietly shrinking it. `assertBoth`
//      additionally fails if either major is missing, so a recording captured on one box only
//      cannot look like a pass.
//   2. **It normalises nothing on either side of an image comparison.** That is the one test
//      underwriting the WYSIWYG promise, and normalising is how it passes while being useless.
//   3. **It asserts the INPUT, not just the output.** A recording of Ghost's answer with no record
//      of Ghost's question can only assert that a string equals itself. Every case below feeds the
//      shim the recorded input and compares against the recorded output.
//
// The recordings are imported, not read: AD-1 bans `node:fs` inside a core package and the
// test-file exemption gives back only `node:test` and `node:assert`. `fixtures/index.ts` is
// generated by the capture command over whatever is on disk, so a template added to the probe theme
// cannot go unasserted through a stale import list.

