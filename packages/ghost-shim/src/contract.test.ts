// ─── reading a recording, and failing by NAME when there is none ──────────────

const MAJORS = ['5', '6'] as const
type Major = (typeof MAJORS)[number]

type Recording = {
  template: string
  path: string
  uploaded_image: string
  ghost_version: string
  captured: string
  command: string
  site: string
  image_sizes: Record<string, number>
  values: Record<string, Record<string, unknown>>
  raw: Record<string, unknown>
  input: Record<string, unknown>
}

function recording(major: Major, template: string, helper: string): Recording {
  const box = RECORDINGS[`ghost${major}`]
  const rec = box?.[template] as Recording | undefined
  if (rec === undefined) {
    throw new Error(
      `NO RECORDING for "${helper}" — ghost${major}/${template}.json is absent. Capture it: ` +
        `${CAPTURE_COMMAND} ${major}. A contract test with no recording FAILS, naming the helper ` +
        `and the capture command; it never skips and it never passes vacuously (standing rule 2).`,
    )
  }
  return rec
}

/** One recorded value, or a named failure. `group` and `key` are the probe theme's own
 *  `GROUP|key=[…]` coordinates, so a refusal points at the line to add. */
function recorded(major: Major, template: string, group: string, key: string, helper: string): string {
  const rec = recording(major, template, helper)
  const g = rec.values[group]
  if (g === undefined || !Object.prototype.hasOwnProperty.call(g, key)) {
    throw new Error(
      `NO RECORDING for "${helper}" — ghost${major}/${template}.json carries no ${group}|${key}. ` +
        `Add the line to tools/probe/theme-shim/${template.replace(/-page-\d+$/, '')}.hbs and ` +
        `re-run: ${CAPTURE_COMMAND} ${major}.`,
    )
  }
  return String(g[key])
}

function input<T>(major: Major, template: string, key: string, helper: string): T {
  const rec = recording(major, template, helper)
  const v = rec.input[key]
  if (v === undefined) {
    throw new Error(`NO RECORDED INPUT for "${helper}" — ghost${major}/${template}.json has no input.${key}. Re-run: ${CAPTURE_COMMAND}`)
  }
  return v as T
}

/** Runs one assertion per major and requires BOTH to be present. A difference between the majors is
 *  expressed, never averaged: the callback receives the major, so a case that legitimately differs
 *  asserts each side's own recorded string. */
function assertBoth(helper: string, body: (major: Major) => void): void {
  const missing = MAJORS.filter((m) => RECORDINGS[`ghost${m}`] === undefined)
  assert.deepEqual(
    missing,
    [],
    `"${helper}" has no recording for Ghost ${missing.join(' and ')}. Both majors are targets ` +
      `(NFR-7): capture with ${CAPTURE_COMMAND}.`,
  )
  for (const m of MAJORS) body(m)
}

// ─── standing rule 2's own control: the failure path FAILS ────────────────────
//
// "A result whose control did not pass is not a result." The whole suite rests on `recorded()`
// throwing rather than returning undefined when a helper has no recording, so that claim is itself
// asserted — a suite that would silently shrink to nothing if the fixtures went missing is not a
// contract test, and three probes in one session have already returned a convincing "held" that was
// really a broken test.

test('a helper with no recording FAILS, naming the helper and the capture command', () => {
  for (const [fn, what] of [
    [() => recording('6', 'no-such-template', '{{invented}}'), 'a missing template'],
    [() => recorded('6', 'index', 'IMG', 'no_such_key', '{{invented}}'), 'a missing value'],
    [() => input('6', 'index', 'no_such_input', '{{invented}}'), 'a missing input'],
  ] as const) {
    assert.throws(
      fn,
      (e: unknown) => {
        const m = (e as Error).message
        assert.match(m, /\{\{invented\}\}/, `${what}: the failure must name the helper`)
        assert.ok(m.includes(CAPTURE_COMMAND), `${what}: the failure must name the capture command`)
        return true
      },
      `${what} must fail, not skip`,
    )
  }
})

